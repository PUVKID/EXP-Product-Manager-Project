    public static class TermsGate
    {
        private static string OkPath { get { return Path.Combine(Paths.Root, "terms.ok"); } }

        public static bool Check()
        {
            string want = TermsText.Version + "|" + License.GetMachineId();
            try { if (File.Exists(OkPath) && File.ReadAllText(OkPath).StartsWith(want)) return true; } catch { }
            using (var f = new TermsForm())
            {
                if (f.ShowDialog() != DialogResult.OK) return false;
                try { Directory.CreateDirectory(Paths.Root); File.WriteAllText(OkPath, want + "|" + DateTime.Now.ToString("o")); } catch { }
                return true;
            }
        }
    }

